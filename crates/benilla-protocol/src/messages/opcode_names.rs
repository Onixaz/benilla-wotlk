//! Every 3.3.5a world opcode's name, generated from AzerothCore
//! `src/server/game/Server/Protocol/Opcodes.h` (1310 entries, deduped by number, sorted), cut at
//! 12340's dispatch bound `0x51F` (`reference/3.3.5a-opcodes.tsv`):
//!
//! ```sh
//! sed -n '/^enum Opcodes/,/^};/p' Opcodes.h \
//!   | sed -nE 's/^[[:space:]]+([A-Z_0-9]+)[[:space:]]*=[[:space:]]*(0x[0-9A-F]+),.*/\2 \1/p' \
//!   | awk '{v = strtonum($1)} v < 0x51F && !seen[v]++ {printf "    (0x%04X, \"%s\"),\n", v, $2}'
//! ```
//!
//! For diagnostics only (the dropped-packet tally, skip logs); dispatch uses [`super::opcode`].

/// The 3.3.5a name of a world opcode in either direction, by binary search of the sorted table.
pub fn opcode_name(opcode: u16) -> Option<&'static str> {
    NAMES
        .binary_search_by_key(&opcode, |&(n, _)| n)
        .ok()
        .map(|i| NAMES[i].1)
}

